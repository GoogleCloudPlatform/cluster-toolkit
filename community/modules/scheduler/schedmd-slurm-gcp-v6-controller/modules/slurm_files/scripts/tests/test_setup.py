def test_is_controller_nfs_server_resolves_controller_zone_fqdn_under_zonal_dns():
    import setup_network_storage

    cfg = TstCfg(
        project="hpc-proj",
        slurm_cluster_name="scalem1",
        slurm_control_host="scalem1-controller",
        slurm_control_addr=None,
    )
    cfg.controller_zone = "projects/hpc-proj/zones/us-central1-a"  # type: ignore[attr-defined]
    lkp = util.Lookup(cfg)

    with patch("setup_network_storage.socket.gethostbyname") as ghbn:
        assert (
            setup_network_storage._is_controller_nfs_server(
                "scalem1-controller.us-central1-a.c.hpc-proj.internal", lkp
            )
            is True
        )
        ghbn.assert_not_called()

    def zonal_resolve(host: str) -> str:
        if host == "10.0.0.2" or host == "scalem1-controller.us-central1-a.c.hpc-proj.internal":
            return "10.0.0.2"
        raise OSError(f"ZonalOnly NXDOMAIN for {host}")

    with patch("setup_network_storage.socket.gethostbyname", side_effect=zonal_resolve):
        assert setup_network_storage._is_controller_nfs_server("10.0.0.2", lkp) is True
