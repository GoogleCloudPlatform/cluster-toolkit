def test_configure_cluster_dns_search_adds_cross_region_zones(tmp_path):
    from common import TstNodeset

    resolv = tmp_path / "resolv.conf"
    resolv.write_text(
        "# Generated by NetworkManager\n"
        "search us-east4-a.c.hpc-proj.internal c.hpc-proj.internal google.internal\n"
        "nameserver 169.254.169.254\n"
    )
    cfg = TstCfg(
        project="hpc-proj",
        slurm_cluster_name="scalem1",
        nodeset={
            "c": TstNodeset(nodeset_name="c", zone_policy_allow=["us-central1-a", "us-central1-ai1a", "us-central1-b"]),
            "e": TstNodeset(nodeset_name="e", zone_policy_allow=["us-east4-a", "us-east4-c"]),
        },
    )
    cfg.controller_zone = "us-central1-a"  # type: ignore[attr-defined]
    lkp = util.Lookup(cfg)

    with patch.object(
        setup,
        "run",
        side_effect=[
            Mock(returncode=0, stdout="2: eth0    default via 10.0.0.1 dev eth0 proto dhcp\n"),
            Mock(returncode=0, stdout="rdma0:eth1\nWired connection 1:eth0\nlo:lo\n"),
            Mock(returncode=0, stdout=""),
            Mock(returncode=0, stdout=""),
        ],
    ) as run_mock:
        setup.configure_cluster_dns_search(lkp, resolv_path=resolv)

    assert run_mock.call_count == 4
    assert "Wired connection 1" in run_mock.call_args_list[2].args[0]
    assert "+ipv4.dns-search" in run_mock.call_args_list[2].args[0]
    merged = resolv.read_text()
    assert "us-central1-a.c.hpc-proj.internal" in merged
    assert "us-central1-b.c.hpc-proj.internal" in merged
    assert "us-east4-c.c.hpc-proj.internal" in merged
    # Standard zones must precede -ai zones in search order
    assert merged.index("us-central1-b.c.hpc-proj.internal") < merged.index(
        "us-central1-ai1a.c.hpc-proj.internal"
    )
    assert merged.strip().splitlines()[1].endswith("google.internal")


def test_populate_etc_hosts_skips_ephemeral_non_ha_controller_ip_and_pins_static(tmp_path):
    hosts = tmp_path / "hosts"
    initial = (
        "127.0.0.1 localhost\n"
        "10.0.32.5 scalem1-east4n2d-0.us-east4-a.c.hpc-proj.internal scalem1-east4n2d-0 # Added by Google\n"
    )
    hosts.write_text(initial)
    cfg = TstCfg(
        project="hpc-proj",
        slurm_cluster_name="scalem1",
        slurm_control_host="scalem1-controller",
        slurm_control_addr=None,
    )
    cfg.controller_zone = "us-central1-a"  # type: ignore[attr-defined]
    lkp = util.Lookup(cfg)

    # 1. Ephemeral non-HA controller (slurm_control_addr=None) must NOT pin a stale IP in /etc/hosts
    with patch.object(util.Lookup, "is_controller", new=False):
        setup.populate_etc_hosts(lkp, hosts_path=hosts)
    assert hosts.read_text() == initial

    # 2. Static IP / HA controller (slurm_control_addr set) pins the explicit address cleanly
    cfg.slurm_control_addr = "10.0.0.2"
    setup.populate_etc_hosts(lkp, hosts_path=hosts)
    updated = hosts.read_text()
    assert "10.0.32.5 scalem1-east4n2d-0.us-east4-a.c.hpc-proj.internal" in updated
    assert "10.0.0.2 scalem1-controller" in updated


def test_setup_sudoers_scopes_nfsd_to_controller_and_blocks_flag_injection(tmp_path):
    sudoers_file = tmp_path / "slurm"
    orig_path = setup.Path

    def fake_path(arg):
        if str(arg) == "/etc/sudoers.d/slurm":
            return sudoers_file
        return orig_path(arg)

    lkp = Mock()
    with patch.object(setup, "Path", side_effect=fake_path), \
         patch.object(setup.util, "lookup", return_value=lkp):
        # 1. Compute / login nodes must NOT receive nfsconf or rpc.nfsd sudoers rules
        lkp.is_controller = False
        setup.setup_sudoers()
        worker_text = sudoers_file.read_text()
        assert "nfsconf" not in worker_text
        assert "rpc.nfsd" not in worker_text
        sudoers_file.unlink()

        # 2. Controllers receive '--' argument-terminated single-arg rules
        lkp.is_controller = True
        setup.setup_sudoers()
        ctrl_text = sudoers_file.read_text()
        assert "/usr/sbin/nfsconf --set -- nfsd threads [1-9]*" in ctrl_text
        assert "!/usr/sbin/nfsconf --set -- nfsd threads * *" in ctrl_text
        assert "/usr/sbin/rpc.nfsd -- [1-9]*" in ctrl_text
        assert "!/usr/sbin/rpc.nfsd -- * *" in ctrl_text


