func writeLLMsFiles(cat Catalog, llmsTxtPath, llmsFullTxtPath string) error {
	if llmsTxtPath != "" {
		content := RenderLLMsTxt(cat)
		if err := os.WriteFile(llmsTxtPath, []byte(content), 0644); err != nil {
			return fmt.Errorf("writing %s: %w", llmsTxtPath, err)
		}
	}
	if llmsFullTxtPath != "" {
		content := RenderLLMsFullTxt(cat)
		if err := os.WriteFile(llmsFullTxtPath, []byte(content), 0644); err != nil {
			return fmt.Errorf("writing %s: %w", llmsFullTxtPath, err)
		}
	}
	return nil
}

