// RenderLLMsFullTxt renders the compact, single-view root llms-full.txt reference from the Catalog.
func RenderLLMsFullTxt(cat Catalog) string {
	var sb strings.Builder
	sb.WriteString(llmsFullTxtHeader)
	renderReservationVars(&sb, cat.Blueprints, "   ", false)
	sb.WriteString("\n## 1. Blueprints Reference\n")
	for _, bp := range cat.Blueprints {
		renderBlueprintFullSection(&sb, bp)
	}
	sb.WriteString("\n## 2. Embedded Modules Reference\n\n")
	sb.WriteString("| Module Source | Required GCP APIs (`gcloud services enable`) | Required Inputs (excl. globals) | Recommended Upstream (`use:`) | Consumed By Downstream |\n")
	sb.WriteString("| :--- | :--- | :--- | :--- | :--- |\n")
	sources := make([]string, 0, len(cat.ModuleWiring))
	for src := range cat.ModuleWiring {
		sources = append(sources, src)
	}
	sort.Strings(sources)
	for _, src := range sources {
		renderModuleFullRow(&sb, src, cat.ModuleWiring[src])
	}
	return sb.String()
}

func renderBlueprintFullSection(sb *strings.Builder, bp BlueprintEntry) {
	mt := "-"
	if len(bp.MachineTypes) > 0 {
		mt = strings.Join(bp.MachineTypes, ", ")
	}
	deployMeta := ""
	if bp.DeploymentPath != "" {
		deployMeta = fmt.Sprintf(" | deployment: `%s`", bp.DeploymentPath)
	}
	fmt.Fprintf(sb, "\n### %s (`%s` | scheduler: `%s` | machines: `%s`%s)\n", bp.Path, bp.BlueprintName, bp.Scheduler, mt, deployMeta)
	if bp.Description != "" {
		fmt.Fprintf(sb, "- **Description:** %s\n", bp.Description)
	}
	apis := "none"
	if len(bp.RequiredServices) > 0 {
		apis = fmt.Sprintf("`gcloud services enable %s`", strings.Join(bp.RequiredServices, " "))
	}
	deployCmd := fmt.Sprintf("`./gcluster deploy %s --vars project_id=<PROJECT_ID>,deployment_name=<DEPLOYMENT_NAME>,region=<REGION>,zone=<ZONE>`", bp.Path)
	if bp.DeploymentPath != "" {
		deployCmd = fmt.Sprintf("`./gcluster deploy -d %s %s`", bp.DeploymentPath, bp.Path)
	}
	fmt.Fprintf(sb, "- **APIs & Deploy:** %s | %s\n", apis, deployCmd)
	renderBlueprintVarsCompact(sb, bp.Vars)
	renderBlueprintModulesCompact(sb, bp.Modules)
}

