func (s *MySuite) TestWrapDeployErr(c *C) {
	// nil stays nil so the happy path is unchanged
	c.Check(wrapDeployErr(nil, "depl/primary"), IsNil)

	orig := errors.New("terraform apply failed: Unsupported argument on main.tf line 71")
	wrapped := wrapDeployErr(orig, "depl/primary")
	c.Assert(wrapped, NotNil)

	var he config.HintError
	c.Assert(errors.As(wrapped, &he), Equals, true)
	c.Check(errors.Is(wrapped, orig), Equals, true)
	c.Check(he.Err, Equals, orig)

	// The hint must point back at the source, name the group dir, and give the re-run commands.
	for _, want := range []string{
		`"depl/primary"`,
		"generated by",
		"must not be edited directly",
		"blueprint YAML",
		"deployment.yaml",
		"create <blueprint.yaml> -d <deployment.yaml> -w",
		"deploy <deployment_dir>",
	} {
		c.Check(strings.Contains(he.Hint, want), Equals, true, Commentf("hint missing %q: %s", want, he.Hint))
	}
	// Rendered error keeps the original message and adds the hint.
	c.Check(strings.Contains(wrapped.Error(), orig.Error()), Equals, true)
	c.Check(strings.Contains(wrapped.Error(), he.Hint), Equals, true)
}

